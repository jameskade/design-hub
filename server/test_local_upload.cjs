const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(path.join(__dirname,'../sketch-plugin/DesignHub.sketchplugin/Contents/Sketch/local-upload.js'),'utf8');
const context=vm.createContext({require:()=>({}),NSFileManager:{defaultManager:()=>({})},module:{exports:{}}});
vm.runInContext(source,context);
const split=context.module.exports.splitAssets;
const items=Array.from({length:53},(_,index)=>({index,data_base64:'test'}));
const batches=split(items);
assert.deepEqual(Array.from(batches,b=>b.length),[24,24,5]);
assert.deepEqual(Array.from(batches.flat(),a=>a.index),items.map(a=>a.index));
const large={data_base64:'a'.repeat(3*1024*1024)};
assert.equal(split([large,large]).length,2);
assert.equal(split([{data_base64:'x'.repeat(5*1024*1024)}]).length,1,'单个较大资源保留完整，不截断');
assert.equal(split([]).length,0);
console.log('PASS: 本地上传按数量/体积分包，顺序保持、无资源丢失、不静默截断');
